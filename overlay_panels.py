def ladder_name(path_key):
    """A path's display name. Module-level for the same reason `wrap_mail` is
    (LAW 9): it is a helper, and helpers on a mixin are one collision away
    from shadowing somebody else's."""
    import ladder as ladder_mod
    return (ladder_mod.path(path_key) or {}).get("name", "")


def wrap_mail(text, width=MAIL_WRAP):
    """Break a paragraph into lines of at most `width` characters.

    A MODULE FUNCTION, NOT A MIXIN METHOD, and that is LAW 9 rather than
    style: `DrawMixin._wrap` already exists, shares a host with this class,
    and caps its output at three lines for the caption box. Adding a second
    `_wrap` here silently shadowed one of them — the letter body came out
    empty on the first run of the panel test. A helper that belongs to no
    class cannot collide with one that does.
    """
    out, line = [], ""
    for word in (text or "").split():
        if line and len(line) + 1 + len(word) > width:
            out.append(line)
            line = word
        else:
            line = (line + " " + word) if line else word
    if line:
        out.append(line)
    return out

# Height the caption box is allowed to occupy on the bottom edge, so the
# career prompt can stack above it instead of on top of it.
CAPTION_STACK = 118

# TRACK MAP learning. The cloud is bounded by geometry rather than by time:
# a point is only kept when the car has actually moved MAP_MIN_STEP metres
# since its last sample, so a finished outline stops growing by itself and a
# parked car cannot pile a thousand points onto one spot.
MAP_MIN_STEP = 12.0     # metres between samples for one car
MAP_MAX_PTS = 4000      # hard ceiling, ~7km of circuit at that spacing

# How many new points the outline may gain before the baked image is redrawn.
# See `_map_image`: rebuilding on every new point is the per-frame cost this
# exists to remove. 25 points is about a second of learning on a full grid and
# is invisible on a picture made of four thousand dots.
MAP_BAKE_STEP = 25

# Supersample factor for the baked outline. Tk's canvas has no antialiasing at
# all, so the OLD per-point path drew hard-edged dots; rendering at 2x and
# downscaling is what makes the outline read as a line rather than as gravel.
# 2 rather than the gauge's 3 because dots have no curves to alias.
MAP_SS = 2


def _lumin(hexcol):
    """How light a #rrggbb colour is, 0..1. Rec. 601, like `_logo_ink`."""
    h = (hexcol or "").lstrip("#")
    if len(h) != 6:
        return 0.0
    r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    return (0.299 * r + 0.587 * g + 0.114 * b) / 255.0


