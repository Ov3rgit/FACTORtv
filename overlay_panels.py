        # THE ONE MESSAGE IN THE PRODUCT THAT CAN BE ANSWERED, and it is
        # answered here rather than by a link inside the letter — because
        # saying yes costs him a round of a championship, and a decision that
        # expensive belongs behind the same confirmation as everything else
        # that cannot be undone.
        # THE FIA LETTER IS WHERE HE PICKS HIS CAR.
        #
        # Asked for: "instead of it telling me which car is eligible, give the
        # player a select option ... let the player pick which between these 2
