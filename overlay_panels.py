        # that itself — it returns None for anything not on the news feed —
        # and the reason is the ending: the personal letters only work
        # because they are indistinguishable from licensing statements, and
        # "which ones have pictures" is a thing a reader would sort by.
        pic = None
        try:
            div = (car.evaluate() or {}).get("tier_name") or car.name
            pic = newsart.for_item(m, div)
        except Exception:
            pic = None
        if pic:
            rows.append({"kind": "image", "path": pic, "label": ""})
        for line in wrap_mail(m.get("subject", ""), MAIL_WRAP - 8):
            rows.append({"label": line, "kind": "text"})
        rows.append({"label": "", "kind": "text"})
