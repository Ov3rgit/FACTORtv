    # -- sector strip -----------------------------------------------------------
    def draw_sectors(self, s):
        """Your current lap, split by sector, coloured against your bests.

        Purple = session best, green = your personal best, yellow = neither.
        This is the one readout that tells you whether the lap you are ON is
        actually any good, which the lap TIME cannot do until it is over.
        """
        me = s.player if s else None
        if me is None or not self.show_sectors or s.kind == "test":
            self._sector_rect = None
            self._hide_panel("sectors")
            return

        w, h = UI(250), UI(56)
        gx, gy, gw, gh = self.game_rect
        x, y = gx + UI(EDGE), gy + gh - h - UI(EDGE)
        self._sector_rect = (x, y, w, h)
        p = self._begin_panel("sectors", x, y, w, h)
        c = p.canvas_at(x, y)
        self._body(c, x, y, w, h)

        self._label(c, x + UI(10), y + UI(6), "CURRENT LAP")
        best = me.best_lap
        c.create_text(x + w - UI(10), y + UI(10), anchor="ne",
                      text=fmt_lap(best), fill=TH.dim, font=self.f_tiny)

        segs = (me.last_s1, me.last_s2, me.last_s3)
        bests = (s.best_s1, s.best_s2, s.best_s3)
        mine = (me.best_s1, me.best_s2, me.best_s3)

        sw = (w - UI(24)) / 3.0
        for i in range(3):
            sx = x + UI(12) + i * sw
            sy = y + UI(24)
            v = segs[i]
            col = self._sector_colour(v, bests[i], mine[i])
            # The sector you are IN is outlined rather than filled: it has no
            # time yet, and filling it would imply one.
            live = (me.sector == i + 1)
            c.create_rectangle(sx, sy, sx + sw - UI(4), sy + UI(20),
                               fill="" if live else mix(TH.panel, col, 0.55),
                               outline=col if live else shade(TH.border, 1.2),
                               width=2 if live else 1)
            c.create_text(sx + UI(4), sy + UI(4), anchor="nw",
                          text=SECTOR_LABELS[i], fill=TH.dim, font=self.f_tiny)
            c.create_text(sx + sw - UI(8), sy + UI(10), anchor="e",
                          text=("%.3f" % v) if v else "--.---",
                          fill=TH.text, font=self.f_row)

    def _sector_colour(self, v, session_best, personal_best):
        if not v:
            return TH.dim
        if session_best and v <= session_best + 1e-4:
            return TH.best
        if personal_best and v <= personal_best + 1e-4:
            return TH.good
        return TH.warn

    # -- track map ---------------------------------------------------------------
    def draw_map(self, s):
        """A learned outline of the circuit with live car positions.

        rF2's plugin gives world coordinates per car but no track geometry, so
        the shape here is LEARNED: every car's position is sampled into a
        point cloud during the session and normalised to the panel. One lap of
        running is enough for a recognisable outline, and it costs nothing on
        a track nobody has ever seen.
        """
        if not self.show_map or s is None or not s.order:
            self._map_rect = None
            self._hide_panel("map")
            return
        self._map_learn(s)
        pts = self._map_pts
        if len(pts) < 40:
            self._hide_panel("map")
            return

        # Bottom-LEFT, stacked above the sector strip. The right-hand corner
        # belongs to the dash; putting the map there meant one of them had to
        # be pushed toward the middle, which the layout law forbids.
        size = UI(190)
        gx, gy, gw, gh = self.game_rect
        x = gx + UI(EDGE)
        y = gy + gh - size - UI(EDGE)
        if self.show_sectors:
            y -= UI(56) + UI(10)
        self._map_rect = (x, y, size, size)
        p = self._begin_panel("map", x, y, size, size)
        c = p.canvas_at(x, y)
        self._body(c, x, y, size, size)

        pad = UI(16)
        inner = size - pad * 2

        # THE OUTLINE IS BAKED, NOT REDRAWN.
        #
        # This loop used to issue one `create_oval` per learned point, every
        # frame — up to MAP_MAX_PTS of them, 20 times a second, to redraw a
        # shape that by definition does not move. Profiling the whole frame
        # (`frametime.py`) put the map at ~11ms, the most expensive panel in
        # the product and a fifth of the entire tick budget, for a picture
        # that was identical to the one before it.
        #
        # It is now rendered once into a PIL image and blitted as a single
        # `create_image` — the same trick, for the same reason, as the
        # instrument in `gauge.py`, which is where the RGB-flatten and
        # chroma-key lessons below come from. Only the CAR DOTS remain as
        # canvas items, because those are the only things that actually
        # change from frame to frame.
        img = self._map_image(pts, size, pad, inner)
        if img is not None:
            # The baked image carries the panel background with it, so it is
            # blitted OVER the body and the border and spine are re-stroked
            # on top. Two canvas items to keep the panel furniture defined in
            # exactly one place, against up to four thousand it replaces.
            c.create_image(x, y, image=img, anchor="nw")
            self._map_photo = img       # a PhotoImage the canvas does not own
            c.create_rectangle(x, y, x + size, y + size, fill="",
                               outline=TH.border, width=1)
            c.create_rectangle(x, y, x + 3, y + size, fill=TH.accent,
                               outline="")
        else:                           # no PIL: the honest old path
            for wx, wz in pts:
                px, py = self._map_proj(wx, wz, x + pad, y + pad, inner)
                c.create_oval(px - 1, py - 1, px + 1, py + 1,
                              fill=shade(TH.border, 1.4), outline="")

        for car in s.order:
            if car.pos is None:
                continue
            px, py = self._map_proj(car.pos[0], car.pos[1],
                                    x + pad, y + pad, inner)
            if car is s.player:
                col, r = TH.you, UI(5)
            elif car.place == 1:
                col, r = TH.leader, UI(4)
            else:
                col, r = TH.dim, UI(3)
            c.create_oval(px - r, py - r, px + r, py + r, fill=col,
                          outline=shade(TH.panel, 0.5))

    def _map_learn(self, s):
        """Sample positions into the outline cloud.

        Three things this has to get right, and it got all three wrong:

        1. THE CLOUD MUST RESET WHEN THE TRACK CHANGES. It never did, so
           running Silverstone after Monza drew both circuits on top of each
           other and normalised the pair into a smear. Keyed on the track
           name, which is the only thing guaranteed to change.

        2. IT MUST NOT STOP LEARNING MID-LAP. Six cars sampled every 0.15s is
           forty points a second, so the old 1400-point cap was reached in
           about thirty-five seconds — less than one lap of a long circuit,
           leaving the outline permanently unfinished.

        3. IT MUST IGNORE THE PIT LANE AND STATIONARY CARS. A car sitting in
           the garage piles hundreds of identical points on one spot, which
           drags the bounds and flattens the rest of the shape.

        Points are now kept only when they are a real distance from the last
        one sampled for that car, which bounds the cloud by GEOMETRY rather
        than by time — a finished outline stops growing on its own.
        """
        if not hasattr(self, "_map_pts") or getattr(self, "_map_track", None) != s.track:
            self._map_pts = []
            self._map_bounds = None
            self._map_last = 0.0
            self._map_seen = {}
            self._map_track = s.track
        now = time.time()
        if now - self._map_last < 0.10 or len(self._map_pts) > MAP_MAX_PTS:
            return
        self._map_last = now
        for car in s.order[:8]:
            if car.pos is None or car.in_pits or getattr(car, "in_garage", False):
                continue
            x, z = car.pos[0], car.pos[1]
            prev = self._map_seen.get(car.id)
            if prev is not None:
                dx, dz = x - prev[0], z - prev[1]
                if (dx * dx + dz * dz) < MAP_MIN_STEP * MAP_MIN_STEP:
                    continue
            self._map_seen[car.id] = (x, z)
            self._map_pts.append((x, z))
        xs = [p[0] for p in self._map_pts]
        zs = [p[1] for p in self._map_pts]
        if xs:
            self._map_bounds = (min(xs), max(xs), min(zs), max(zs))

    def _map_image(self, pts, size, pad, inner):
        """The learned outline, baked into one image.

        Returns a PhotoImage to blit, or None if PIL is unavailable — in
        which case the caller falls back to the per-point canvas loop, which
        is correct, just slow.

        THE CACHE KEY IS THE POINT. The cloud GROWS while a session is being
        learned, so a key on the exact point count would rebuild every time a
        car moved twelve metres — that is the per-frame cost back again with
        an image encoder bolted on. Keyed on a BUCKET of the count instead,
        so the picture is at most `MAP_BAKE_STEP` points stale while learning
        and completely static once the outline is finished, which is the
        state a race spends nearly all of its time in.

        The bounds are in the key because a new extreme re-normalises every
        point on the map; the theme colours are in it because the palette
        follows the era, and a cached Monza in 1988 colours would otherwise
        survive the change of skin.
        """
        if not _HAVE_PIL:
            return None
        b = self._map_bounds
        key = (self._map_track, len(pts) // MAP_BAKE_STEP, int(size), int(pad),
               tuple(round(v, 1) for v in (b or ())), TH.panel, TH.border)
        if key == getattr(self, "_map_key", None):
            return self._map_photo
        im = Image.new("RGB", (size * MAP_SS, size * MAP_SS), TH.panel)
        d = ImageDraw.Draw(im)
        col = shade(TH.border, 1.4)
        r = MAP_SS                      # one screen pixel, supersampled
        for wx, wz in pts:
            px, py = self._map_proj(wx, wz, pad, pad, inner)
            px, py = px * MAP_SS, py * MAP_SS
            d.ellipse((px - r, py - r, px + r, py + r), fill=col)
        im = im.resize((size, size), Image.LANCZOS)
        # RGB, never RGBA. An RGBA PhotoImage with varied alpha costs ~65ms to
        # hand to Tk against 0.3ms for the same picture as RGB — the lesson
        # `gauge.py` paid for. The background is baked in instead.
        self._map_key = key
        self._map_photo = ImageTk.PhotoImage(im)
        return self._map_photo

    def _map_proj(self, wx, wz, ox, oy, inner):
        """World coords -> panel pixels, aspect-preserved.

        Preserving aspect matters: stretching to fill the panel turns every
        circuit into the same blob and destroys the one thing a map is for,
        which is being recognisable.
        """
        b = self._map_bounds
        if not b:
            return ox, oy
        x0, x1, z0, z1 = b
        span = max(x1 - x0, z1 - z0, 1.0)
        px = ox + (wx - x0) / span * inner + (inner - (x1 - x0) / span * inner) / 2
        py = oy + (wz - z0) / span * inner + (inner - (z1 - z0) / span * inner) / 2
        return px, py

    # -- podium -------------------------------------------------------------------
    def draw_podium(self, s):
        """The classification, once it means something.

        Only after the flag. A "podium" mid-race is just the top three, which
        the tower already shows.
        """
        if not s or not s.finished or not s.order:
            self._hide_panel("podium")
            return
        rows = s.order[:3]
        if not rows:
            return

        w = UI(420)
        rh = UI(44)
        h = UI(44) + len(rows) * rh + UI(12)
        gx, gy, gw, gh = self.game_rect
        x, y = gx + (gw - w) / 2.0, gy + gh / 2 - h / 2
        p = self._begin_panel("podium", x, y, w, h)
        c = p.canvas_at(x, y)
        self._body(c, x, y, w, h)

        # WHAT KIND OF RESULT THIS IS. It said "RACE RESULT" after a
        # qualifying session — the panel was written for the flag at the end
        # of a race and then reused for the end of every session, which is
        # the right reuse and the wrong caption.
        kind = {"quali": "QUALIFYING RESULT",
                "practice": "PRACTICE RESULT",
                "warmup": "WARM-UP RESULT"}.get(getattr(s, "kind", "race"),
                                                "RACE RESULT")
        c.create_text(x + w / 2, y + UI(22), text=kind,
                      fill=TH.text, font=self.f_small)
        c.create_text(x + w / 2, y + UI(36), text=self._short_track(s.track).upper(),
                      fill=TH.dim, font=self.f_tiny)

        # THE DIVISION'S MARK, top right of the card. It is the one place in
        # the product where a result sits still long enough to be looked at,
        # so it is worth saying which championship it belongs to.
        #
        # Cached and RGB-flattened by the same helper the corner mark uses —
        # onto the PANEL colour here rather than the chroma key, because this
