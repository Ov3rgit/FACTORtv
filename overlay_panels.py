    # HOW LONG THE NEXT DIVISION LASTS — asked for directly: *"can we not
    # choose race length also when we get a promotion? for example if I want to
    # do only a 3 race season for karting but then a 5 race season for F4."*
    #
    # `advance(rounds=...)` and `_start_rung` have taken a length since the
    # ladder was wired; nothing ever passed one, so every rung inherited the
    # number chosen once at the top of the career. That was a defensible
    # default and a poor rule: the whole point of a ladder is that the
    # divisions are not the same size of commitment, and a driver who wants
    # three rounds of karting is not saying he wants three rounds of Formula
    # One.
    #
    # THE SAME THREE LENGTHS THE NEW-CAREER PAGE OFFERS. One vocabulary for
    # "how long is a season" across the product, so the number he picks at a
    # promotion means exactly what it meant when he started.
    SEASON_LENGTHS = (3, 5, 10)

    def _next_length(self, car):
        """Rounds the NEXT rung will run to: his pending choice, or this one."""
        pend = getattr(self, "_next_len", None)
        if pend:
            return int(pend)
        return int((car.total_rounds if car is not None else 0) or 0)

    def _next_is_finale(self, car):
        """Is the rung he is about to move into the LAST of its path?"""
        try:
            import ladder as ladder_mod
            if car is None or not car.on_ladder:
                return False
            prog = car.ladder
            if prog is None:
                return False
            ts = ladder_mod.tiers(prog.path)
            if not ts or (ladder_mod.path(prog.path) or {}).get("tour"):
                return False
            return (prog.reached + 1) == len(ts) - 1
        except Exception:
            return False

    def _rows_nextlen(self):
        """How many rounds the division he is moving into should run to.

        IT IS ASKED, NEVER ASSUMED, and it defaults to the length he has been
        racing — so a driver who ignores this page gets exactly the behaviour
        the career had before it existed.
        """
        car = getattr(self, "season", None)
        cur = int((car.total_rounds if car is not None else 0) or 0)
        pend = getattr(self, "_next_len", None)
        # A FINALE IS NOT A CHOICE, so the page must not pretend to offer one.
        # The last division of a path always runs to ten rounds — it is the
        # championship that finishes an arc and counts toward the 100%, and a
        # three-round version of it would skip the whole challenge. Offering a
        # picker the store will overrule is worse than not offering one.
        import season as season_mod
        fin = self._next_is_finale(car)
        if fin:
            return [{"label": "Next season", "kind": "info",
                     "note": "%d races" % season_mod.FINALE_ROUNDS},
                    {"label": "The last division of this path", "kind": "info",
                     "note": "fixed"},
                    {"label": "It is the championship that finishes the arc",
                     "kind": "text", "quiet": True},
                    {"label": "and the one the 100%% counts, so its length is "
                              "not yours to set.", "kind": "text",
                     "quiet": True},
                    {"label": "Back", "key": "page_ladder", "kind": "nav",
                     "note": "<"}]
        rows = [{"label": "Next season", "kind": "info",
                 "note": "%d races" % self._next_length(car)}]
        if cur:
            rows.append({"label": "Same as this season",
                         "key": "nextlen:0", "kind": "action",
                         "note": ("%d races  •" % cur if not pend
                                  else "%d races" % cur)})
        for n in self.SEASON_LENGTHS:
            if n == cur:
                continue
            rows.append({"label": "%d races" % n, "key": "nextlen:%d" % n,
                         "kind": "action",
                         "note": "any circuit  •" if pend == n
                                 else "any circuit"})
        rows.append({"label": "Back", "key": "page_ladder", "kind": "nav",
                     "note": "<"})
        return rows

    def _rows_ladder(self):
        """What happens now the season is over.

        Every row here is DESTRUCTIVE — it archives the standings and clears
        the season — so every one of them routes through the confirmation
        page, exactly as deleting a career does.
        """
        car = getattr(self, "season", None)
        ev = (car.evaluate() if car is not None and car.on_ladder else None)
        if not ev:
            return [{"label": "No ladder season", "kind": "info"},
                    {"label": "Back",
                     "key": "page_%s" % getattr(self, "_ladder_back", "career"),
                     "kind": "nav", "note": "<"}]
        pos = ev.get("pos")
        rows = [{"label": ev["tier_name"], "kind": "info",
                 "note": "finished P%d" % pos if pos else "no result"}]
        if not ev.get("complete"):
            rows.append({"label": "Season is not over yet", "kind": "info",
                         "note": "%d rounds" % len(car.rounds)})
        elif ev.get("promoted"):
            rows.append({"label": "Take the %s seat" % ev["next_name"],
                         "key": "adv:promote", "kind": "action",
                         "note": "earned"})
        elif ev.get("arc_done"):
            # THE ARC IS FINISHED — he won the final championship. The FIA's
            # permission to compete elsewhere is the reward, and it is the
            # only route that counts toward a 100% career.
            rows.append({"label": "%s — champion" % ev["path_name"],
                         "kind": "info",
                         "note": "%d%% career" % round(
                             (ev.get("career_pct") or 0) * 100)})
            for p in (ev.get("next_paths") or [])[:4]:
                for idx, nm, reg in p["entries"]:
                    rows.append({"label": "%s: %s" % (p["name"][:10], nm[:11]),
                                 "key": "adv:newpath:%s:%d" % (p["key"], idx),
                                 "kind": "action", "note": reg[:11]})
        elif ev.get("top"):
            rows.append({"label": "Nothing above this", "kind": "info",
                         "note": "the top division"})
        else:
            rows.append({"label": "Missed the cut", "kind": "info",
                         "note": "needed P%s" % (ev.get("needs") or "?")})
        if ev.get("complete"):
            # THE LENGTH SITS WITH THE CHOICES IT APPLIES TO. It governs
            # whichever of them he takes — the seat above, another go at this
            # division, a switch, a new path — so it belongs beside all four
            # rather than on a page he would have to know to visit first.
            _fin = self._next_is_finale(car)
            rows.append({"label": "Next season length", "key": "page_nextlen",
                         "kind": "nav",
                         "note": ("10 races, fixed >" if _fin
                                  else "%d races >" % self._next_length(car))})
            rows.append({"label": "Stay in %s" % ev["tier_name"],
                         "key": "adv:retry", "kind": "action",
                         "note": "go again"})
            for pkey, idx, name in (ev.get("sideways") or [])[:4]:
                rows.append({"label": "Move to %s" % name,
                             "key": "adv:switch:%s:%d" % (pkey, idx),
                             "kind": "action", "note": "another path"})
        rows.append({"label": "Back",
                     "key": "page_%s" % getattr(self, "_ladder_back", "career"),
                     "kind": "nav", "note": "<"})
        return rows

