    def _sim_grid(self, car):
        """Who else is in a simulated round. [] if we cannot know.

        THE LOCKED CLASS IS NOT AVAILABLE YET, and that was the bug: `cls` is
        filled in by the first race a season RECORDS, so a career that has not
        raced has none — which is exactly the career somebody wants to
        simulate from. The lookup found nothing, the sim had no grid, and it
        refused silently.

        So the roster is found by RUNG: any class `career.py` has ever seen
        that resolves to the division he is standing in. That is the same list
        the New Career driver picker is built from, and it exists as soon as
        he has loaded the cars once — in practice, after a single practice
        session in them.
        """
        hist = getattr(self, "career", None)
        if car is None or hist is None:
            return []
        classes = (hist.data.get("classes") or {})
        names = []
        cls = car.data.get("cls") or ""
        if cls and cls in classes:
            names = list((classes[cls] or {}).get("drivers") or [])
        if not names:
            try:
                import ladder as ladder_mod
                prog = car.ladder
                want = (prog.path, prog.reached) if prog is not None else None
            except Exception:
                want = None
            if want:
                for key, blk in classes.items():
                    try:
                        if ladder_mod.tier_of(car_class=key) != want:
                            continue
                    except Exception:
                        continue
                    for nm in (blk or {}).get("drivers") or ():
                        if nm and nm not in names:
                            names.append(nm)
        return [n for n in names if n and n != (car.me or "")]

    def _sim_blocked(self, car):
        """Why this round cannot be simulated yet, or None.

        THE SIM IS NOT A SHORTCUT PAST SETTING UP A CAREER. The user found he
        could simulate a round before choosing a car or a nationality, which
        banks a result for a season that is not configured — and a career
        cannot be un-raced.

        Returned as a REASON rather than a bare False, because a disabled
        button that does not say why is the thing he actually complained
        about: he pressed it, confirmed, and nothing happened.
        """
        if car is None:
            return "no career"
        if not car.next_round():
            return "season complete"
        if not (car.me or "").strip():
            return "pick a name first"
        if getattr(car, "on_ladder", False) and not car.nationality:
            return "pick a nationality"
        try:
            import ladder as ladder_mod
            prog = car.ladder
            tier = (prog.tier() or {}) if prog is not None else {}
            cars = ladder_mod.tier_cars(tier) if tier else []
        except Exception:
            cars = []
        if len(cars) > 1 and not car.car_pick():
            return "pick a car first"
        if not self._sim_grid(car):
            # No form and no roster: there is nobody to race. Say so rather
            # than banking a round he was alone in.
            return "race them once first"
        return None

    def draw_settings(self):
        """Everything else is click-through so the mouse always belongs to
        the game; this one deliberately is not, and it is only ever on screen
        when the user asked for it."""
        if not self.menu_open:
            self._hide_panel("menu")
            return

        rows = self._menu_rows()
        # THE MAIL PAGES ARE WIDER, because they are the only ones with prose
        # on them. A letter wrapped to a 300px column is a letter nobody
        # reads, which would quietly undo the whole reason the inbox is
        # written as correspondence.
        reading = getattr(self, "menu_page", "main") in ("inbox", "mail")
        w = UI(MAIL_W if reading else 300)
        rh = UI(30)
        # A `text` row is a wrapped line of a letter and gets its own, much
        # tighter height — twenty body lines at menu spacing is a panel taller
        # than the screen.
        trh = UI(17)
        # A NEWS PICTURE IS A ROW LIKE ANY OTHER, so the panel grows to fit it
        # rather than the image being drawn over the words underneath. One
        # aspect ratio (16:9) for every photograph, cropped to it — a feed
        # where each article is a different shape is a feed that looks broken
        # rather than illustrated.
        imw = w - UI(20) * 2
        imh = int(imw * 9 / 16.0)
        # THE DASHBOARD'S OWN ROWS HAVE THEIR OWN HEIGHTS. A career screen made
        # of thirty identical grey rows is a page you read rather than a page you
        # glance at, which is the wrong shape for the one screen a driver opens
        # between sessions.
        def _row_h(r):
            k = r.get("kind")
            if k == "image":
                return imh + UI(10)
            if k == "logo":
                return UI(26)
            if k == "text":
                return trh
            if k == "head":
                return UI(58)
            if k == "tiles":
                return UI(52)
            if k == "bar":
                return UI(34)
            if k == "gap":
                return UI(8)
            if k == "band":
                return UI(20)
            return rh

        h = UI(46) + UI(12) + sum(_row_h(r) for r in rows)
        gx, gy, gw, gh = self.game_rect
        # Below the hamburger, so the button stays visible and clickable
        # while the panel is open.
        x = gx + UI(EDGE)
        y = gy + UI(EDGE) + UI(CONTROL_H) + UI(CONTROL_GAP)
        p = self._begin_panel("menu", x, y, w, h, clickable=True)
        c = p.canvas_at(x, y)
        self._body(c, x, y, w, h)

