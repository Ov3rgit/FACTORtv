    # -- the division's mark ----------------------------------------------------
    #
    # Asked for directly: the logo of the division he is in, top right, in a
    # race and out of one, changing when he takes the seat above.
    #
    # WHY THE TOP RIGHT IS SAFE HERE AND WAS NOT FOR THE INBOX. The relative
    # panel owns that corner — which is why the envelope went top LEFT — but
    # it starts at `y + 78` and nothing else draws in the band above it. So
    # the mark sits in a gap that already existed rather than displacing a
    # panel the driver reads every lap.
    # THE MARK FILLS THE BAND IT LIVES IN.
    #
    # The relative panel starts at y+78 and the screen edge margin is 18, so
    # there are exactly 60 logical pixels of clear space up there. The first
    # version used 42 of them plus a 12px box, which the user reported as
    # "way too small" and he was right — a third of the available height was
    # going to a frame nobody asked for.
    #
    # Any taller than this and it collides with the relative panel, which is
    # a thing he reads every lap. If it ever needs to be bigger than the band
    # allows, the honest options are to move it down the right-hand edge or
    # to push the relative panel down — both of which move something the
    # driver is looking at, so neither is done on a guess.
    LOGO_H = 56             # the mark's height; width follows its own ratio
    LOGO_MAX_W = 320        # ...unless the ratio would run it into the middle

    def _logo_photo(self, path, h, w_max, bg):
        """The mark, scaled and cached, as something Tk will blit.

        THE TWO LESSONS FROM `gauge.py`, both of which cost real frames when
        they were learned there:

        * FLATTEN TO RGB. An RGBA PhotoImage with varied alpha takes ~65ms to
          hand to Tk; the same picture as RGB takes 0.3ms. A logo is a PNG
          with a transparent background, so this is exactly that case — and
          it is composited onto the panel colour, which is why `bg` is part
          of the cache key.
        * CACHE THE SCALED COPY. This is drawn every frame. Re-opening and
          resampling a 1000px PNG twenty times a second would cost more than
          every other panel put together.
        """
        key = (path, h, w_max, bg)
        cache = getattr(self, "_logo_cache", None)
        if cache is None:
            cache = self._logo_cache = {}
        if key in cache:
            return cache[key]
        try:
            from PIL import Image, ImageTk
            im = Image.open(path).convert("RGBA")
            # TRIM THE EMPTY MARGIN FIRST, or the marks come out at wildly
            # different visual sizes for no reason the user can see. These
            # are downloaded PNGs and each one has a different amount of
            # transparent padding baked in — the Formula One mark is a wide
            # logo centred in a square image, so scaling its RAW height made
            # it half the size of the Formula 4 one beside it. Cropping to
            # the artwork means "56 pixels tall" means the same thing for
            # every division.
            box = im.getbbox()
            if box:
                im = im.crop(box)
            scale = float(h) / max(1, im.height)
            w = int(im.width * scale)
            if w > w_max:                       # a very wide mark
                scale = float(w_max) / max(1, im.width)
                w = w_max
            im = im.resize((max(1, w), max(1, int(im.height * scale))),
                           Image.LANCZOS)
            if bg == CHROMA:
                # A BLACK RING ROUND THE MARK — reported by the user, and it
                # is what alpha blending onto a chroma key always does.
                #
                # `-transparentcolor` is BINARY: a pixel is either exactly
                # #010102 and the game shows through, or it is opaque. A
                # LANCZOS resize leaves every edge pixel partly transparent,
                # and blending those against a near-black ground produced a
                # dark fringe that the key could not remove — so the mark
                # arrived outlined in black, worst of all over the bright
                # scenery the user photographed it against.
                #
                # So the edge is keyed rather than blended: above the
                # threshold the pixel keeps its OWN colour, below it the
                # ground shows through. Aliased edges are the price of a
                # binary key, and they are invisible next to a halo.
                flat = Image.new("RGB", im.size, CHROMA)
                mask = im.getchannel("A").point(
                    lambda a: 255 if a >= LOGO_ALPHA_CUT else 0)
                flat.paste(im.convert("RGB"), (0, 0), mask)
                # A HOLE IN A LOGO IS WORSE THAN A BOX ROUND IT. The key is an
                # exact colour, so a pixel of ARTWORK that happens to be that
                # value is punched through with the background — and these
                # marks are black on transparent, so it is a live risk.
                #
                # ONLY WHERE THE ARTWORK IS. An earlier version walked every
                # pixel and nudged anything equal to the key, including the
                # background, which is that colour ON PURPOSE — that put the
                # black box back. The mask is what separates "the mark happens
                # to be this colour" from "this is the hole the game shows
                # through".
                px, mp = flat.load(), mask.load()
                ckey = tuple(int(CHROMA[i:i + 2], 16) for i in (1, 3, 5))
                safe = (ckey[0], ckey[1], min(255, ckey[2] + 2))
                for yy in range(flat.height):
                    for xx in range(flat.width):
                        if mp[xx, yy] and px[xx, yy] == ckey:
                            px[xx, yy] = safe
            else:
                # A REAL GROUND TAKES THE BLEND. On a letterhead or a menu row
                # the mark sits on a known panel colour, so the soft edge is
                # correct there and is what keeps small marks legible.
                flat = Image.new("RGB", im.size, bg)
                flat.paste(im, (0, 0), im)
            photo = ImageTk.PhotoImage(flat)
        except Exception:
            # A corrupt or unreadable file is not a crash. The overlay simply
            # has no mark for that division, which is the same state as not
            # having made the folder yet.
            photo = False
        cache[key] = photo
        return photo

    def _logo_ink(self, path):
        """How dark this mark's own ink is, 0..1, or None if it cannot be read.

        A DARK MARK ON A DARK CARD IS NOT A MARK. The karting logo is maroon
        line-art with transparency, so `_logo_plate` correctly says it needs no
        plate — and it still came out nearly invisible on the dashboard's header.
        The Formula One mark is the opposite case and proves a blanket plate is
        wrong: white ink on a white tile disappears just as completely.

        So it is MEASURED. The mean luminance of the pixels that are actually
        opaque, which is the only thing that decides whether the mark needs
        something light behind it.

        Cached with the paths: this opens and scans a file, and the header is
        drawn every frame the dashboard is open.
        """
        cache = getattr(self, "_ink_cache", None)
        if cache is None:
            cache = self._ink_cache = {}
        if path in cache:
            return cache[path]
        lum = None
        try:
            from PIL import Image
            im = Image.open(path).convert("RGBA")
            im.thumbnail((48, 48))
            tot, n = 0.0, 0
            px = im.load()
            for yy in range(im.height):
                for xx in range(im.width):
                    r, g, b, a = px[xx, yy]
                    if a < 128:
                        continue
                    tot += (0.299 * r + 0.587 * g + 0.114 * b) / 255.0
                    n += 1
            if n:
                lum = tot / n
        except Exception:
            lum = None
        cache[path] = lum
        return lum

    def _logo_plate(self, path):
        """Does this mark need a light plate behind it?

        True when the file carries no transparency — a JPEG, or a PNG saved
        flat. Such a mark was drawn against a white page by whoever made it,
        and its dark text only exists because of that white.

        Cached with the paths, because it is asked every frame the letter is
        open and it opens the file to answer.
        """
        cache = getattr(self, "_plate_cache", None)
        if cache is None:
            cache = self._plate_cache = {}
        if path in cache:
            return cache[path]
        need = False
        try:
            from PIL import Image
            im = Image.open(path)
            need = im.mode not in ("RGBA", "LA") and "transparency" not in im.info
        except Exception:
            need = False
        cache[path] = need
        return need

    def draw_division_logo(self):
        """The current division's logo, top right.

        Shown whenever a career is loaded, in a session or out of one — the
        same contract as the mode badge, and for the same reason: which
        championship he is in is true between races as well as during them.

        It reads `evaluate()["tier_name"]`, which is the same source the mode
        badge and the divisions view read, so the mark and the words beneath
        it can never disagree about which championship this is. When he takes
        the seat above, `advance()` moves the rung and the mark follows on the
        next frame with nothing to invalidate by hand.
        """
        car = getattr(self, "season", None)
        if car is None or not getattr(car, "on_ladder", False):
            self._hide_panel("divlogo")
            return
        ev = car.evaluate() or {}
        name = ev.get("tier_name")
        path = newsart.logo(name) if name else None
        if not path:
            # NO FOLDER, NO MARK — and never somebody else's. A photograph of
            # unfamiliar racing is atmosphere; the wrong LOGO is a claim about
            # which championship he is driving in, and this product has been
            # wrong about that once already.
            self._hide_panel("divlogo")
            return
        h = UI(self.LOGO_H)
        photo = self._logo_photo(path, h, UI(self.LOGO_MAX_W), CHROMA)
        if not photo:
            self._hide_panel("divlogo")
            return
        # NO PANEL BEHIND IT. The user: "the logo mustn't be on a
        # background". The window is chroma-keyed, so compositing the mark
        # onto CHROMA lets it float over the road the way a broadcast bug
        # does — and it is the same trick the dash used before it moved onto
        # a card. The slab treatment is right for panels full of numbers and
        # wrong for a single graphic.
        w, box = photo.width(), photo.height()
        gx, gy, gw, gh = self.game_rect
        x = gx + gw - w - UI(EDGE)
        y = gy + UI(EDGE)
        p = self._begin_panel("divlogo", x, y, w, box)
        c = p.canvas_at(x, y)
        c.create_image(x, y, image=photo, anchor="nw")
        # Tk drops an image the instant nothing references it, and the canvas
        # item does NOT count as a reference. Held here, per panel, or the
        # logo flickers out on the next garbage collection.
        p._logo_ref = photo

