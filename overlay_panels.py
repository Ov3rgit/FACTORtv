    def menu_click(self, sx, sy):
        """Handle a click at screen coordinates. True if it hit something."""
        b = getattr(self, "_inbox_btn_rect", None)
        if b and b[0] <= sx <= b[2] and b[1] <= sy <= b[3]:
            # THE TROPHY OPENS THE CAREER DASHBOARD, or closes it if that is
            # already what is showing — one button, one obvious meaning. It used
            # to open the post directly; the post now lives one row inside the
            # dashboard, which is the screen this button is actually about.
            if self.menu_open and getattr(self, "menu_page", "") == "dash":
                self.menu_open = False
            else:
                self.menu_open = True
                self.menu_page = "dash"
                self._mail_offset = 0
            self._menu_confirm = None
            return True
        b = getattr(self, "_menu_btn_rect", None)
        if b and b[0] <= sx <= b[2] and b[1] <= sy <= b[3]:
            self.menu_open = not self.menu_open
            # Always reopen on the main page. Returning to a half-finished
            # delete confirmation minutes later is a way to lose a season.
            self.menu_page = "main"
            self._menu_confirm = None
            return True
        # THE INTRODUCTION SURVIVES THE BUTTONS IT IS POINTING AT.
        #
        # It said "any click ends it" and it meant it, including the click it had
        # just asked for: the script says *open the trophy and start a career*,
        # so following the instruction cancelled the lesson. He put it plainly —
        # *"you said it was a click to end it, but i need to click the trophy
        # thing whcih i do then it ends it, so i dont know what you mean"*.
        #
        # Opening the menu or the trophy IS the tutorial working. Anything else —
        # a row, a toggle, a page — is a man who has started doing something of
        # his own, and being talked at through that is the tutorial nobody
        # finishes. So the two button branches above return before ever reaching
        # this, and everything below it stops the talking.
        if getattr(self, "_tut_i", 0) and not getattr(self, "_tut_done_seen",
                                                      False):
            try:
                self.tutorial_stop()
                self._tut_done_seen = True
            except Exception:
                pass
        if not self.menu_open:
            return False
        for key, x0, y0, x1, y1 in getattr(self, "_menu_hits", ()):
            if x0 <= sx <= x1 and y0 <= sy <= y1:
                if key.startswith("slider:"):
                    # The bar's own ends travel with the key, because the row
                    # that drew them is long gone by the time a click arrives.
                    name, bx0, bx1 = key[7:].split("|")
                    bx0, bx1 = float(bx0), float(bx1)
                    frac = (sx - bx0) / max(1.0, bx1 - bx0)
                    self._menu_slide(name, max(0.0, min(1.0, frac)))
                    return True
                self._menu_hit(key)
                return True
        return False

    def _menu_slide(self, name, frac):
        """A slider moved. Rounded to 5% steps so the value is sayable and so
        the scaled-audio cache stays small."""
        from factor_tv import save_settings
        val = round(frac * 20) / 20.0
        if name == "vol":
            self.cfg["volume"] = val
            try:
                self.tts.set_volume(val)
            except Exception:
                pass
            save_settings(self.cfg)

    def _menu_hit(self, key):
        # THE NEWS IS THE INBOX WITH THE OTHER FEED SELECTED, and the dashboard
        # links straight to it — a driver who wants the news should not have to
        # open the post and then switch tabs.
        if key == "page_news":
            self._mail_feed = "news"
            self._mail_offset = 0
            self.menu_page = "inbox"
            return
        if key == "page_inbox":
            self._mail_feed = "mail"
            self._mail_offset = 0
            self.menu_page = "inbox"
            return
        if key.startswith("page_"):
            # BACK GOES WHERE HE CAME FROM. The end-of-season page is now
            # reachable from the inbox as well as the career page, and a Back
            # button that always returns to Career would strand a man who
            # arrived from his post two screens from where he started.
            if key == "page_ladder":
                self._ladder_back = ("inbox"
                                     if getattr(self, "menu_page", "") == "inbox"
                                     else "dash")
            if key == "page_divisions":
                # Straight off the dashboard, or one level down from the career
                # record. Both are real routes and Back has to honour whichever
                # he took.
                self._div_back = ("record"
                                  if getattr(self, "menu_page", "") == "record"
                                  else "dash")
            self.menu_page = {"career": "career", "new": "career_new",
                              "load": "career_load", "delete": "career_delete",
                              "len": "career_len", "cls": "career_cls",
                              "name": "career_name",
                              "inbox": "inbox", "mail": "mail",
                              "record": "record", "divisions": "divisions",
                              "standings": "standings", "results": "results",
                              "nation": "career_nation", "legal": "legal",
                              "path": "career_path", "plen": "career_plen",
                              "ladder": "career_ladder",
                              "nextlen": "career_nextlen",
                              "dash": "dash",
                              "main": "main"}.get(key[5:], "main")
            return
        if key in ("confirm_yes", "confirm_no"):
            q, act, arg = getattr(self, "_menu_confirm", None) or ("", "", None)
            self._menu_confirm = None
            self.menu_page = "career"
            if key == "confirm_yes" and act:
                self._menu_action(act, arg)
            return
        if key == "confirm_deal":
            car = getattr(self, "season", None)
            try:
                import programme as prog_mod
                blk = prog_mod.signed(car)[1] or {}
            except Exception:
                blk = {}
            if car is not None and blk:
                # THE COST IS THE POINT OF THE BEAT, so it is said out loud
                # before he agrees to it.
                self._menu_confirm = (
                    "Take the %s seat? You sit out %s and start in 2021."
                    % (blk.get("f1_team") or "the", prog_mod.TEST_YEAR),
                    "deal_now", None)
                self.menu_page = "confirm"
            return
        if key == "sim_round":
            car = getattr(self, "season", None)
            nxt = car.next_round() if car is not None else None
            if car is not None and nxt and not self._sim_blocked(car):
                total = car.total_rounds or 0
                # THE WARNING IS THE WHOLE OF THE PROTECTION. The user's call
                # was that the finale stays simulatable and says plainly what
                # it costs — his career, his decision, made with his eyes
                # open rather than refused by a menu.
                q = ("Simulate the FINAL round? The title may be decided by a "
                     "race you did not drive."
                     if total and nxt.get("n") == total
                     else "Simulate round %d?" % nxt["n"])
                self._menu_confirm = (q, "sim_now", str(nxt.get("n") or 0))
                self.menu_page = "confirm"
            return
        if key.startswith("progpick:"):
            # CONFIRMED. It decides which Formula One door opens, it cannot be
            # taken back, and a mis-click here would quietly rewrite the rest
            # of the career.
            pkey = key.split(":", 1)[1]
            car = getattr(self, "season", None)
            if car is not None and pkey:
                try:
                    import programme as prog_mod
                    b = prog_mod.get(pkey) or {}
                    label = b.get("f2_team") or pkey
                except Exception:
                    label = pkey
                self._menu_confirm = ("Sign for %s?" % label,
                                      "progpick_now", pkey)
                self.menu_page = "confirm"
            return
        if key.startswith("carpick:"):
            # CONFIRMED, because it is the season's car and cannot be undone
            # by racing again — the same gate as deleting a career or taking
            # the story's offer.
            folder, _, nice = key.split(":", 1)[1].partition("|")
            car = getattr(self, "season", None)
            if car is not None and folder:
                if not nice:
                    try:
                        import ladder as ladder_mod
                        nice = ladder_mod.pretty_mod(folder)
                    except Exception:
                        nice = folder
                self._menu_confirm = ("Race the %s this season?" % nice,
                                      "carpick_now", "%s|%s" % (folder, nice))
                self.menu_page = "confirm"
            return
        if key in ("story_yes", "story_no"):
            car = getattr(self, "season", None)
            if car is not None:
                self._menu_confirm = (
                    ("Miss the next round?" if key == "story_yes"
                     else "Stay and race?"),
                    "story_now", key[6:])
                self.menu_page = "confirm"
            return
        if ":" in key or key in ("drop_last", "career_none", "mail_readall"):
            act, _, arg = key.partition(":")
            self._menu_action(act, arg or None)
            return
        self._menu_toggle(key)

    def _menu_action(self, act, arg=None):
        import season as season_mod
        from factor_tv import save_settings
        if act == "pick":
            # Chosen a preset; now choose how long the season is.
            self._menu_preset = arg
            self.menu_page = "career_len"

        elif act == "len":
            # ...and now which car class it is a championship for.
            key, _, n = (arg or "").partition(":")
            self._menu_preset = key
            self._menu_rounds = int(n or 0)
            self.menu_page = "career_cls"

        elif act == "mail":
            # OPENING A LETTER MARKS IT READ, at the moment it is opened
            # rather than when the list was drawn (LAW 11 — a flag belongs to
            # the thing happening, not to the thing being offered).
            import inbox as inbox_mod
            car = getattr(self, "season", None)
            if car is not None:
                inbox_mod.read(car, arg)
            self._mail_open = arg
            self.menu_page = "mail"

        elif act == "mailpage":
            self._mail_offset = int(arg or 0)

        elif act == "sim_now":
            car = getattr(self, "season", None)
            if car is not None:
                nxt = car.next_round() or {}
                # THE GRID COMES FROM WHAT HE OWNS. With no rounds raced there
                # is no form to simulate from, so the roster `career.py`
                # learned for this class stands in — the same list the New
                # Career driver picker is built from.
                names = self._sim_grid(car)
                r = car.simulate_round(n=nxt.get("n"),
                                       slug=nxt.get("slug", ""),
                                       event=nxt.get("event", ""),
                                       names=names)
                if r is not None:
                    # EVERYTHING THAT WOULD HAVE ARRIVED, ARRIVES. The result
                    # sheet, the standings piece, the FIA notices and her
                    # letters all read the store, so banking the round and
                    # refreshing is the whole of it — asked for directly:
                    # "all news reports and FIA and emails and Mel
                    # notifications must be simulated in as well".
                    try:
                        import inbox as inbox_mod
                        import news as news_mod
                        import personal as personal_mod
                        inbox_mod.refresh(car)
                        news_mod.refresh(car)
                        personal_mod.refresh(car)
                    except Exception:
                        pass
            self.menu_page = "career"

        elif act == "progpick_now":
            car = getattr(self, "season", None)
            if car is not None and arg:
                try:
                    import programme as prog_mod
                    import inbox as inbox_mod
                    if prog_mod.accept(car, arg):
                        # The confirmation letter is generated immediately, so
                        # the decision has a receipt in the archive rather
                        # than only a changed menu row.
                        inbox_mod.refresh(car)
                except Exception:
                    pass
            self.menu_page = "inbox"

        elif act == "carpick_now":
            car = getattr(self, "season", None)
            if car is not None and arg:
                _folder, _, _nice = arg.partition("|")
                car.pick_car(_folder, _nice or None)
            self.menu_page = "mail"

        elif act == "story_now":
            car = getattr(self, "season", None)
            if car is not None:
                import personal as personal_mod
                personal_mod.answer(car, arg == "yes")
            self.menu_page = "inbox"

        elif act == "mailfeed":
            # Switching tab resets the paging. Landing on page three of the
            # news because that is where the inbox was left is a small thing
            # that feels broken every single time.
            self._mail_feed = arg or "mail"
            self._mail_offset = 0

        elif act == "mail_readall":
            import inbox as inbox_mod
            car = getattr(self, "season", None)
            if car is not None:
                inbox_mod.read_all(car, feed=arg or None)

        elif act == "mail_del":
            # Deleting one letter is small and instant — no confirmation page.
            # It is not a season, the archive is regenerated for everything
            # except this id, and a confirm dialog on every message would make
            # tidying an inbox a chore. Deliberately different from `del`.
            import inbox as inbox_mod
            car = getattr(self, "season", None)
            if car is not None:
                inbox_mod.delete(car, arg)
            self.menu_page = "inbox"

        elif act == "path":
            # Chosen a ladder; now how long one rung's season runs for.
            #
            # A TOUR CARRIES ITS ERA IN THE KEY ("historic:2"), because the eras
            # are unlocked one at a time and which one he was invited to is part
            # of the choice rather than a page after it.
            key, _, era = (arg or "").partition(":")
            self._menu_path = key
            self._menu_tier = int(era) if era.isdigit() else 0
            self.menu_page = "career_plen"

        elif act == "plen":
            # A LADDER CAREER SKIPS THE CLASS PAGE, and that is deliberate:
            # the rung already names every car that belongs to it, in both of
            # the two names a car has. Locking the exact CarClass string on
            # top would tie the season to whichever chassis loaded first.
            # ...AND THE ERA HE WAS INVITED TO. A tour career starts in the era
            # he picked rather than at the bottom of the file: the eras are
            # unlocked one at a time and the sixties may well not be open yet.
            car = season_mod.create("open",
                                    me=self.cfg.get("display_name", ""),
                                    rounds=int(arg or 5),
                                    ladder_path=getattr(self, "_menu_path", ""),
                                    tier_index=getattr(self, "_menu_tier", 0))
            if car is not None:
                # THE UNLOCKS TRAVEL WITH THE DRIVER, NOT WITH THE SAVE FILE. A
                # new career is a clean slate everywhere else in this product,
                # and it should be here too — except that an invitation earned by
                # winning Formula One would then be unusable, because taking it
                # up means starting a career on the tour. So the era he was
                # invited to is opened in the new file, and nothing else is.
                try:
                    if getattr(self, "_menu_path", "") == self._tour_key():
                        old_car = getattr(self, "season", None)
                        if old_car is not None:
                            for k in (old_car.data.get("tour_unlocked") or ()):
                                car.tour_grant(k)
                except Exception:
                    pass
                self._menu_activate(car)
            self._menu_tier = 0
            self.menu_page = "career"

        elif act == "adv":
            # Advancing archives the standings and clears the season, so it
            # never happens on the first click — same rule as a delete.
            car = getattr(self, "season", None)
            ev = (car.evaluate() if car is not None and car.on_ladder else None)
            if not ev:
                return
            what, _, rest = (arg or "").partition(":")
            if what == "promote":
                q = "Move up to %s?" % ev.get("next_name", "the next division")
            elif what == "newpath":
                pkey, _, idx = rest.partition(":")
                import ladder as ladder_mod
                ts = ladder_mod.tiers(pkey)
                i = int(idx or 0)
                q = "Start in %s?" % (ts[i]["name"] if 0 <= i < len(ts)
                                      else "a new path")
            elif what == "switch":
                pkey, _, idx = rest.partition(":")
                import ladder as ladder_mod
                ts = ladder_mod.tiers(pkey)
                i = int(idx or 0)
                q = "Switch to %s?" % (ts[i]["name"] if 0 <= i < len(ts)
                                       else "another path")
            else:
                q = "Race %s again?" % ev.get("tier_name", "this season")
            # ...AND IT SAYS HOW LONG. The length is chosen a page earlier and
            # applied by the same click, so the confirmation has to state both
            # or it is confirming half of what is about to happen.
            n = self._next_length(car)
            if n:
                q = "%s  (%d races)" % (q, n)
            self._menu_confirm = (q, "adv_now", arg)
            self.menu_page = "confirm"

        elif act == "adv_now":
            car = getattr(self, "season", None)
            if car is not None:
                what, _, rest = (arg or "").partition(":")
                pkey, _, idx = rest.partition(":")
                car.advance(what, path_key=pkey, tier_index=int(idx or 0),
                            rounds=getattr(self, "_next_len", None) or None)
                # SPENT ON THE SEASON IT WAS CHOSEN FOR. A pending length left
                # lying around would silently re-apply at the NEXT promotion,
                # which is a season length he chose two divisions ago.
                self._next_len = None
                # The rung changed, so which round a live session belongs to
                # is a different answer now — same reason a loaded career
                # re-arms.
                self._season_armed = False
                self._season_round = None

        elif act == "nextlen":
            # 0 IS "SAME AS THIS SEASON", not zero races. It clears the pending
            # choice rather than storing a number, so the default stays "what he
            # has been racing" even if he changes his mind twice.
            n = int(arg or 0)
            self._next_len = n if n else None
            self.menu_page = "career_ladder"

        elif act == "nation":
            car = getattr(self, "season", None)
            if car is not None:
                car.set_nationality(arg or "")
            self.menu_page = "career"

        elif act == "nationpage":
            self._menu_offset = int(arg or 0)

        elif act == "namepage":
            self._menu_offset = int(arg or 0)

        elif act == "name":
            car = getattr(self, "season", None)
            if car is not None:
                car.set_driver(arg or "")
                self._apply_driver_name()
            self.menu_page = "career"

        elif act == "cls":
            members = (getattr(self, "_menu_cls_members", {}) or {}).get(arg or "")
            car = season_mod.create(getattr(self, "_menu_preset", ""),
                                    me=self.cfg.get("display_name", ""),
                                    rounds=getattr(self, "_menu_rounds", 0),
                                    cls=arg or "", cls_any=members or ())
            if car is not None:
                self._menu_activate(car)
            self.menu_page = "career"

        elif act == "load":
            car = season_mod.load(arg)
            if car is not None:
                self._menu_activate(car)
            self.menu_page = "career"

        elif act == "del":
            # Destructive, so it never happens on the first click.
            name = next((c["name"] for c in season_mod.list_careers()
                         if c["slug"] == arg), arg or "")
            self._menu_confirm = ("Delete '%s'?" % name[:18], "del_now", arg)
            self.menu_page = "confirm"

        elif act == "del_now":
            cur = getattr(self, "season", None)
            season_mod.delete(arg)
            if cur is not None and cur.slug == arg:
                self.season = None
                self.cfg["career"] = ""
                save_settings(self.cfg)

        elif act == "career_none":
            # Closes the career WITHOUT deleting it: the commentary stops
            # referring to a season, the save stays on disk.
            self.season = None
            self.cfg["career"] = ""
            save_settings(self.cfg)

        elif act == "deal_now":
            car = getattr(self, "season", None)
            try:
                import programme as prog_mod
                prog_mod.take_deal(car)
            except Exception:
                pass
            self.menu_page = "dash"

        elif act == "drop_last":
            car = getattr(self, "season", None)
            if car is not None and car.rounds:
                last = sorted(car.rounds, key=lambda r: r.get("when", 0))[-1]
                self._menu_confirm = ("Undo round %d?" % last.get("n", 0),
                                      "drop_now", None)
                self.menu_page = "confirm"

        elif act == "drop_now":
            car = getattr(self, "season", None)
            if car is not None:
                car.drop_last()

    def _apply_driver_name(self):
        """Push the career's driver name into the session tracker.

        `SessionTracker.display_name` is what replaces rF2's "Your Name"
        everywhere — booth, engineer, timing tower — so setting it here is
        all that is needed for the whole broadcast to use it.
        """
        car = getattr(self, "season", None)
        name = (car.data.get("driver") if car else "") or             self.cfg.get("display_name") or None
        try:
            self.tracker.display_name = name
        except Exception:
            pass

    def _menu_activate(self, car):
        from factor_tv import save_settings
        self.season = car
        self._menu_offset = 0
        # A DIFFERENT CAREER IS A DIFFERENT SEASON LENGTH. A pending choice
        # belongs to the career it was made in.
        self._next_len = None
        self._apply_driver_name()
        self.cfg["career"] = car.slug
        save_settings(self.cfg)
        # A career loaded mid-session has to re-match: which round this race
        # belongs to is a different answer now.
        self._season_armed = False
        self._season_round = None

    def _menu_toggle(self, key):
        if key == "intro_replay":
            try:
                self.tutorial_replay()
                self._tut_done_seen = False
                self.menu_open = False      # he is about to be shown the buttons
            except Exception:
                pass
            return
        if key == "importcareers":
            try:
                import season as season_mod
                n = season_mod.import_careers()
            except Exception:
                n = 0
            # THE ROW SAYS WHAT HAPPENED. A click that silently does nothing is
            # how a player concludes the career really is gone.
            self._orphan_msg = (
                "Brought %d career%s across - open Load career"
                % (n, "" if n == 1 else "s") if n
                else "Nothing could be copied")
            return
        if key == "roundcount":
            car = getattr(self, "season", None)
            nxt = car.next_round() if car is not None else None
            if car is not None and nxt:
                car.set_round_counts(nxt["n"], not car.round_counts(nxt["n"]))
                # THE BOOTH HAS TO BE TOLD, because it decided which round this
                # session was when the session loaded. Without this, switching a
                # round off mid-garage would leave the booth still calling it a
                # championship round until the next session change.
                self._season_armed = False
                self._season_round = None
            return
        if key == "career_quali":
            car = getattr(self, "season", None)
            if car is not None:
                car.set_quali(not car.uses_quali)
            return
        if key == "career_record":
            val = not getattr(self, "season_record", True)
            self.season_record = val
            self.cfg["career_record"] = val
            from factor_tv import save_settings
            save_settings(self.cfg)
            return
        attr = {"booth": "booth_enabled", "radio": "radio_enabled",
                "rivals": "rival_enabled", "show_dash": "show_dash",
                "show_tower": "show_tower", "show_relative": "show_relative",
                "show_sectors": "show_sectors", "show_map": "show_map"}[key]
        val = not getattr(self, attr)
        setattr(self, attr, val)
        self.cfg[key] = val
        if key == "radio":
            # Radio and rivals are one feature to a user; the menu still shows
            # them separately for fine control, but muting team radio must not
            # leave rival drivers talking into the silence.
            self.rival_enabled = val
            self.cfg["rivals"] = val
        if not val and key in ("booth", "radio", "rivals"):
            self.tts.interrupt()
        from factor_tv import save_settings
        save_settings(self.cfg)
