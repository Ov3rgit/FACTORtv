    def _rows_inbox(self):
        """The archive. Newest first, unread marked and nothing else marked.

        A NEW MESSAGE LOOKS LIKE EVERY OTHER MESSAGE. No badge, no colour, no
        ceremony beyond a dot for unread — because the story's whole mechanism
        is that by the time the important letter arrives the player has been
        trained to skim. If this list ever starts flagging what matters, the
        ending stops working.
        """
        import inbox as inbox_mod
        import news as news_mod
        car = getattr(self, "season", None)
        if car is None:
            return [{"label": "No career loaded", "kind": "info"},
                    {"label": "Back", "key": "page_dash", "kind": "nav",
                     "note": "<"}]
