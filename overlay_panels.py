    # -- the inbox ----------------------------------------------------------
    #
    # OUT OF THE CAR ONLY, and that is not a limitation — it is the answer to
    # two separate problems that happened to have one solution. The top-right
    # corner is already the relative panel, and you cannot read a letter at
    # 200mph. So during a session the inbox is a BADGE and nothing else, and
