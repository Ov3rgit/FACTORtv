    def _rows_standings(self):
        """The championship table as it stands.

        ASKED FOR BECAUSE OF SIMULATION. A race he drove, he watched; a round
        he simulated produced positions and points and nothing else, so the
        standings are the only place the season is visible at all. Without
        this the sim banks a result into a table nobody can read.

        IT READS `standings()` — the same function the booth quotes and the
        news feed prints. A second tally would eventually disagree with the
        commentary, and the viewer believes the one he can re-read.
        """
        car = getattr(self, "season", None)
        if car is None:
            return [{"label": "No career loaded", "kind": "info"},
                    {"label": "Back", "key": "page_dash", "kind": "nav",
                     "note": "<"}]
        table = car.standings()
        rows = []
        mark = self._season_mark()
        if mark:
            rows.append(mark)
        st = car.title_state() or {}
        done = len(car.rounds)
        total = car.total_rounds or 0
        rows.append({"label": car.name[:22], "kind": "info",
                     "note": ("round %d of %d" % (done, total) if total
                              else "%d rounds" % done)})
        if not table:
            rows.append({"label": "Nothing scored yet", "kind": "info",
                         "note": "race one"})
        me = (car.me or "")
        for i, (name, pts) in enumerate(table[:12], start=1):
            mine = name == me
            rows.append({"label": "%2d  %s" % (i, name[:20]),
                         "kind": "info" if not mine else "text",
                         "quiet": False,
                         "note": "%d pts" % pts})
        # WHAT IT WOULD TAKE, but only when the arithmetic is exact (LAW 4).
        # `title_scenarios` returns None the moment it cannot prove an answer.
        sc = car.title_scenarios()
        if sc and not sc.get("decided") and sc.get("secure"):
            rows.append({"label": "To secure the title", "kind": "info",
                         "note": "finish P%d" % sc["secure"]})
        elif sc and sc.get("decided"):
            rows.append({"label": "The title is decided", "kind": "info",
                         "note": "mathematically"})
        rows.append({"label": "Back", "key": "page_dash", "kind": "nav",
                     "note": "<"})
        return rows

    def _rows_results(self):
        """Every round of this season, and how it went.

        The other half of what a simulated season needs: the table says where
        he stands, this says what happened on the way there.

        A SIMULATED ROUND SAYS SO. It produced positions and points and no
        events, and a results page that hid that would be claiming he drove
        races he did not.
        """
        car = getattr(self, "season", None)
        if car is None:
            return [{"label": "No career loaded", "kind": "info"},
                    {"label": "Back", "key": "page_dash", "kind": "nav",
                     "note": "<"}]
        rows = []
        mark = self._season_mark()
        if mark:
            rows.append(mark)
        rows.append({"label": car.name[:22], "kind": "info",
                     "note": "%d rounds" % len(car.rounds)})
        if not car.rounds:
            rows.append({"label": "No rounds yet", "kind": "info",
                         "note": "race one"})
        for rnd in sorted(car.rounds, key=lambda r: r.get("n") or 0):
            pos = rnd.get("pos") or 0
            if rnd.get("absent"):
                note = "missed"
            elif rnd.get("dnf"):
                note = "DNF"
            else:
                note = "P%d" % pos if pos else "-"
            if rnd.get("simulated"):
                note += "  (sim)"
            where = (rnd.get("event") or rnd.get("slug")
                     or "round %d" % (rnd.get("n") or 0))
            rows.append({"label": "%2d  %s" % (rnd.get("n") or 0,
                                              str(where)[:20]),
                         "kind": "info", "note": note})
        rows.append({"label": "Back", "key": "page_dash", "kind": "nav",
                     "note": "<"})
        return rows

    def _rows_record(self):
        """His career on one page: what he has won, and how long it took.

        EVERY FIGURE IS ONE THE OVERLAY WATCHED. Titles are seasons it scored,
        wins are races it recorded under THE LAW, and the two percentages mean
        different things and say so — career progress runs to three divisions,
        a 100% record to five. This is the screen the booth's own knowledge of
        him is drawn from (`Career.resume`), so if it says something the
        commentary does not, one of them is reading the store wrong.
        """
        car = getattr(self, "season", None)
        r = car.resume() if car is not None else None
        if not r:
            return [{"label": "No ladder career", "kind": "info",
                     "note": "start one"},
                    {"label": "Back", "key": "page_dash", "kind": "nav",
                     "note": "<"}]
        rows = [{"label": (car.me or "Driver")[:24], "kind": "info",
                 "note": r["tier_name"][:20]}]
        rows.append({"label": "Career", "kind": "info",
                     "note": "%d%% — %d of 3 divisions"
                             % (round(r["career_pct"] * 100),
                                len(r["arcs_won"]))})
        rows.append({"label": "Record", "kind": "info",
                     "note": "%d of 5 divisions" % len(r["arcs_won"])})
        for label, val in (("Seasons", r["seasons"]), ("Races", r["races"]),
                           ("Wins", r["wins"]), ("Podiums", r["podiums"]),
                           ("Championships", r["title_count"])):
            rows.append({"label": label, "kind": "info", "note": str(val)})
        # THE SEASONS THEMSELVES, newest first — the shape of a career rather
        # than its totals. A man who won Formula 4 and then finished fifth in
        # Formula 3 twice has a story that no total can show.
        for h in list(reversed(r.get("history") or []))[:5]:
            pos = h.get("pos")
            rows.append({"label": "  " + (h.get("name") or "")[:22],
                         "kind": "info",
                         "note": ("champion" if pos == 1
                                  else "P%d" % pos if pos else "unfinished")})
        rows.append({"label": "Divisions", "key": "page_divisions",
                     "kind": "nav", "note": ">"})
        rows.append({"label": "Back", "key": "page_dash", "kind": "nav",
                     "note": "<"})
        return rows

